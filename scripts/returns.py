#!/usr/bin/env python3
"""Scenario returns for £100 / f100 nominal of EIC vs VOC stock, bought Jan 1725,
sold at the end of a chosen year 1745-1750.

All prices are per 100 nominal (i.e. "per cent of par"), which is how both
markets quoted shares. Dividends are simple sums (no reinvestment), which is
how an 18th-century holder would actually have received them.

Inputs and their sources are documented in notes/02-data-and-calculations.md.
"""

# ---------- EIC dividend rates (% of nominal per year) ----------
# Third Report from the Committee of Secrecy (House of Commons, 1773), dividend table:
#   1722/3 .. 1731/2 at 8%; 1732/3 .. 1742/3 at 7%; 1743/4 .. 1754/5 at 8%.
def eic_rate(year):
    if year <= 1732:
        return 8.0
    if year <= 1743:
        return 7.0
    return 8.0

# ---------- VOC dividend assumptions (% of nominal per year) ----------
# De Pinto (1748): shareholders "barely received twelve" tonnes of gold (f1.2m)
# a year -> 1.2 / 6.44 = ~18.6% of nominal capital. Gaastra: never lower than 12.5%.
VOC_DIV = {"low": 15.0, "central": 18.6, "high": 20.0}

# ---------- Purchase prices, January 1725 ----------
# EIC: Amsterdam quotes 148.5-149 (Oct 1724) and 163.5-167 (Jun 1725), Beach et al. 2013.
EIC_BUY = {"low": 149.0, "central": 157.0, "high": 165.0}
# VOC: Gaastra: "prices ... ran as high as 650 per cent during this year" (1725).
VOC_BUY = 650.0

# ---------- Exit-price scenarios, 1745-1750 ----------
# EIC: 150 = wartime trough level (cf. 1735/1739 Amsterdam quotes ~148-156);
#      170 = average Amsterdam price 1747-1794 (Beach et al.);
#      190 = high end, the 1731 level (Gentleman's Magazine, Jan 1731: India 189),
#            plausible at the post-peace / Pelham-conversion top of late 1749.
EIC_EXIT = {"low": 150.0, "central": 170.0, "high": 190.0}
# VOC: 300 = De Pinto (1748): shares "fallen to half their value of ten years before"
#            (1737: 580-620, Gaastra);
#      400 = trend estimate (GFD: price fell ~2.8%/yr 1719-1794; 650*0.9717**20 ~ 365-450);
#      500 = optimistic: decline from 1737 only modest.
VOC_EXIT = {"low": 300.0, "central": 400.0, "high": 500.0}


def eic_divs(exit_year):
    return sum(eic_rate(y) for y in range(1725, exit_year + 1))


def voc_divs(exit_year, case):
    return VOC_DIV[case] * (exit_year - 1725 + 1)


def multiple(total, cost):
    return total / cost


def annualised(mult, years):
    return mult ** (1 / years) - 1


def main():
    out = []
    out.append("# Scenario results (generated by scripts/returns.py)\n")
    out.append("Values per 100 nominal. 'Multiple' = (dividends received + sale price) / purchase price.\n")
    out.append("## Cumulative EIC dividends by exit year (from 1725 inclusive)\n")
    out.append("| Exit at end of | EIC dividends | VOC dividends (low/central/high) |")
    out.append("|---|---|---|")
    for y in range(1745, 1751):
        out.append(f"| {y} | {eic_divs(y):.0f} | {voc_divs(y,'low'):.0f} / {voc_divs(y,'central'):.0f} / {voc_divs(y,'high'):.0f} |")
    out.append("")

    exit_year = 1749
    yrs = exit_year - 1725 + 1
    out.append(f"## Full scenario grid, exit end of {exit_year} ({yrs} years)\n")
    out.append("| Company | Buy | Dividends | Sell | Total back | Multiple | Annualised (no reinvestment) |")
    out.append("|---|---|---|---|---|---|---|")
    rows = []
    for bcase, buy in EIC_BUY.items():
        for scase, sell in EIC_EXIT.items():
            d = eic_divs(exit_year)
            tot = d + sell
            m = multiple(tot, buy)
            rows.append(("EIC", m))
            out.append(f"| EIC (buy {bcase}, sell {scase}) | {buy:.0f} | {d:.0f} | {sell:.0f} | {tot:.0f} | {m:.2f}x | {annualised(m, yrs)*100:.1f}% |")
    for dcase in VOC_DIV:
        for scase, sell in VOC_EXIT.items():
            d = voc_divs(exit_year, dcase)
            tot = d + sell
            m = multiple(tot, VOC_BUY)
            rows.append(("VOC", m))
            out.append(f"| VOC (div {dcase}, sell {scase}) | {VOC_BUY:.0f} | {d:.0f} | {sell:.0f} | {tot:.0f} | {m:.2f}x | {annualised(m, yrs)*100:.1f}% |")
    eic = [m for c, m in rows if c == "EIC"]
    voc = [m for c, m in rows if c == "VOC"]
    out.append("")
    out.append(f"Worst EIC case: {min(eic):.2f}x. Best VOC case: {max(voc):.2f}x. "
               f"EIC beats VOC in every combination: {min(eic) > max(voc)}.\n")

    # Central-case comparison of 1,000 units of currency invested
    c_eic = (eic_divs(exit_year) + EIC_EXIT['central']) / EIC_BUY['central']
    c_voc = (voc_divs(exit_year, 'central') + VOC_EXIT['central']) / VOC_BUY
    out.append("## Central case, 1,000 invested\n")
    out.append(f"- EIC: 1,000 -> {1000*c_eic:,.0f} ({c_eic:.2f}x)")
    out.append(f"- VOC: 1,000 -> {1000*c_voc:,.0f} ({c_voc:.2f}x)")
    out.append("")

    # Exit-year sensitivity for EIC at central buy, showing dividend accrual
    out.append("## EIC central case by exit year (sale price held at 170 except 1749 top = 190 in 'peak' column)\n")
    out.append("| Exit end of | Dividends | Multiple @170 | Multiple @190 |")
    out.append("|---|---|---|---|")
    for y in range(1745, 1751):
        d = eic_divs(y)
        out.append(f"| {y} | {d:.0f} | {(d+170)/EIC_BUY['central']:.2f}x | {(d+190)/EIC_BUY['central']:.2f}x |")
    out.append("")
    text = "\n".join(out)
    print(text)
    return text


if __name__ == "__main__":
    import pathlib, sys
    t = main()
    if len(sys.argv) > 1:
        pathlib.Path(sys.argv[1]).write_text(t)
